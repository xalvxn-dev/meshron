// Copies the legal documents from the Android app (ui/legal/Legal.kt) to the shared screens
// (cross/ui/legal-text.js), so iPhone/Windows show exactly the same text. Run after editing them.
const fs = require('fs')
const path = require('path')
const root = path.join(__dirname, '..')
const k = fs.readFileSync(path.join(root, 'app/src/main/java/com/xalvxnlab/meshron/ui/legal/Legal.kt'), 'utf8')
const contact = /LEGAL_CONTACT = "([^"]+)"/.exec(k)[1]
const version = Number(/LEGAL_VERSION = (\d+)/.exec(k)[1])
const docs = {}
for (const name of ['TERMS', 'PRIVACY', 'GUIDELINES']) {
  const start = k.indexOf('val ' + name + ' = LegalDoc(')
  const end = k.indexOf('\n)\n', start)
  const body = k.slice(start, end)
  const strs = [...body.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => m[1].replace(/\$LEGAL_CONTACT/g, contact).replace(/\\(.)/g, '$1'))
  const [title, updated, intro, ...rest] = strs
  const sections = []
  for (let i = 0; i < rest.length; i += 2) sections.push([rest[i], rest[i + 1]])
  docs[name] = { title, updated, intro, sections }
}
fs.writeFileSync(path.join(root, 'cross/ui/legal-text.js'),
  '// Generated by tools/gen-legal.js from the Android app (ui/legal/Legal.kt). Do not edit by hand.\nwindow.MeshronLegal = ' + JSON.stringify({ version, contact, docs }, null, 1) + '\n')
console.log(Object.values(docs).map((d) => d.title + ': ' + d.sections.length).join(', '))
